/**
 * The atmosphere field behind the hero.
 *
 * WHAT THIS IS. A contour map of the kind Athiti is actually reasoning over —
 * nested isolines around the traveller's position, the places it found, the
 * route between two of them, and the one place it ruled out. The reference
 * implementation this was translated from used a Three.js shader; this uses one
 * inline SVG, and the reason is in `src/styles/athiti.css`. What carried over
 * is the *idea* the shader was standing in for: a slow, deep, quiet field that
 * makes the type feel like it is inside a place rather than on top of a page.
 *
 * WHY THE GEOMETRY IS PROJECTED BY HAND. The six places come from the
 * contract's real `location: GeoPoint`. Rather than hide a web map in the hero,
 * they are projected into the field's own 1200x800 space — a fixed linear
 * transform chosen once, in `project()`, so the node positions are a pure
 * function of the data and move if the fixtures move. Nothing is hard-coded to
 * a screen position.
 *
 * WHY THE DEEP PLANE IS MIRRORED. The contour paths were generated from a radial
 * harmonic function and are drawn once. A second copy is translated by
 * `(-240, 196)`, which reads as a neighbouring landmass rather than a
 * duplicate. Two planes, one geometry.
 */
import type { Experience } from "@/contracts";

/** Fixed projection window. Matches the SVG viewBox. */
const FIELD_W = 1200;
const FIELD_H = 800;

/**
 * Mumbai's bounding box, generously padded. A linear lon/lat fit is not a real
 * map projection and does not need to be — the requirement is that relative
 * positions are truthful and stable, not that distances are.
 */
const LON_MIN = 72.79;
const LON_MAX = 73.15;
const LAT_MIN = 18.9;
const LAT_MAX = 19.16;

function project(point: { lat: number; lon: number }): { x: number; y: number } {
  const x = ((point.lon - LON_MIN) / (LON_MAX - LON_MIN)) * FIELD_W;
  // Latitude increases northward; SVG y increases downward, so this is flipped.
  const y = FIELD_H - ((point.lat - LAT_MIN) / (LAT_MAX - LAT_MIN)) * FIELD_H;
  return { x: round(x), y: round(y) };
}

function round(v: number): number {
  return Math.round(v * 10) / 10;
}

export interface AtmosphereFieldProps {
  experiences: ReadonlyArray<Experience>;
  /** The two places the plan actually chose, in order. Draws the route. */
  routeIds: ReadonlyArray<string>;
  /** The place the plan leads with. Gets the breathing halo. */
  heroId: string;
}

export function AtmosphereField({
  experiences,
  routeIds,
  heroId,
}: AtmosphereFieldProps) {
  const byId = new Map(experiences.map((e) => [e.id, e]));
  const nodes = experiences.map((experience) => {
    const { x, y } = project(experience.location);
    const onRoute = routeIds.includes(experience.id);
    const isHero = experience.id === heroId;
    return { experience, x, y, onRoute, isHero };
  });

  // The two chosen stops, in plan order. If either is missing from the
  // catalogue the line is simply not drawn — never a line to nowhere.
  const [fromId, toId] = routeIds;
  const from = fromId ? byId.get(fromId) : undefined;
  const to = toId ? byId.get(toId) : undefined;
  const a = from ? project(from.location) : null;
  const b = to ? project(to.location) : null;

  return (
    <div className="athiti-field" aria-hidden="true">
      <div className="athiti-parallax" style={{ position: "absolute", inset: 0 }}>
        <svg
          className="athiti-field__svg"
          viewBox={`0 0 ${FIELD_W} ${FIELD_H}`}
          preserveAspectRatio="xMidYMid slice"
          focusable="false"
        >
          <g>{CONTOURS}</g>

          {/* The neighbouring plane. Same geometry, offset, quieter still. */}
          <g transform="translate(-240 196)" opacity="0.5">
            <g>{CONTOURS}</g>
          </g>

          {a && b ? (
            <path className="athiti-route" d={`M${a.x} ${a.y}L${b.x} ${b.y}`} />
          ) : null}

          {nodes.map(({ experience, x, y, onRoute, isHero }) => (
            <g
              key={experience.id}
              className={[
                "athiti-node",
                onRoute ? "athiti-node--route" : "athiti-node--muted",
                isHero ? "athiti-node--hero" : "",
              ]
                .filter(Boolean)
                .join(" ")}
              transform={`translate(${x} ${y})`}
            >
              {isHero ? (
                <circle className="athiti-node__halo" r="9" />
              ) : null}
              <circle className="athiti-node__halo" r="4.5" />
              <circle className="athiti-node__disc" r="2" />
            </g>
          ))}
        </svg>
      </div>
    </div>
  );
}

